#!/usr/bin/env python3
"""Compare CPU BML with a pinned llama.cpp oracle; never download a model.

Build tools/llama_reference.cpp against the reference checkout first. A missing
model returns 77 with status ``not_run``; it never counts as a passed comparison.
All requested comparisons use the fixed F32 tolerance below. They validate
correctness, not comparative throughput or an arbitrary GGUF/model architecture.
"""

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import subprocess
import sys
import time


ROOT = Path(__file__).resolve().parents[1]
REFERENCE_COMMIT = "785322d17f2d51e5185cf996a1f4e46d87640841"
ABSOLUTE_TOLERANCE = 1e-4
RELATIVE_TOLERANCE = 1e-4
PROMPTS = ["Once upon a time", "Hello", "  café\n世界 😀", "The little girl"]
TOKENIZER_PROMPTS = ["", " ", "a  b\t\r\n", "<s>literal</s>", "é🚀中\u00a0e\u0301"]


def sha256(path):
    """Hash input/artifact bytes with bounded memory."""
    digest = hashlib.sha256()
    with Path(path).open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def revision(path):
    """Read the source revision without changing the checkout."""
    return subprocess.run(
        ["git", "-C", str(path), "rev-parse", "HEAD"],
        text=True, check=True, capture_output=True,
    ).stdout.strip()


def working_tree_dirty(path):
    """Identify evidence from an uncommitted checkout instead of claiming HEAD."""
    return bool(subprocess.run(
        ["git", "-C", str(path), "status", "--porcelain", "--untracked-files=normal"],
        text=True, check=True, capture_output=True,
    ).stdout)


def changed_files(snapshot):
    """Detect inputs or executables replaced during the multi-process corpus."""
    errors = []
    for path, expected_hash in snapshot.items():
        try:
            actual_hash = sha256(path)
        except OSError as error:
            errors.append(f"validation input became unavailable: {path}: {error}")
            continue
        if actual_hash != expected_hash:
            errors.append(f"validation input changed during the corpus: {path}")
    return errors


def write_json(path, value):
    """Persist reports atomically and prohibit non-finite JSON numbers."""
    temporary = Path(path).with_suffix(".tmp")
    temporary.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def reject_constant(value):
    raise ValueError(f"non-finite JSON constant: {value}")


def invoke(command, prefix, timeout):
    """Run one process, preserving stdout/stderr and failing on bad JSON/status."""
    prefix = Path(prefix)
    with prefix.with_suffix(".json").open("w") as output, prefix.with_suffix(".stderr.log").open("w") as errors:
        completed = subprocess.run(command, stdout=output, stderr=errors, timeout=timeout, check=False)
    if completed.returncode:
        raise RuntimeError(f"exit status {completed.returncode}; see {prefix.with_suffix('.stderr.log')}")
    with prefix.with_suffix(".json").open() as output:
        result = json.load(output, parse_constant=reject_constant)
    if not isinstance(result, dict):
        raise ValueError("inference output must be a JSON object")
    return result


def ids(value, name):
    if not isinstance(value, list) or not all(type(item) is int and item >= 0 for item in value):
        raise ValueError(f"{name} must be a list of nonnegative token IDs")
    return value


def rows(output):
    """Validate the prefill-plus-each-generated-token logits contract."""
    tokens = ids(output.get("tokens"), "tokens")
    if not ids(output.get("prompt_tokens"), "prompt_tokens"):
        raise ValueError("the prompt must contain at least one token")
    if not isinstance(output.get("text"), str):
        raise ValueError("generated text must be a string")
    data = output.get("bytes")
    if not isinstance(data, list) or not all(type(byte) is int and 0 <= byte <= 255 for byte in data):
        raise ValueError("generated bytes must be a list of byte values")
    values = output.get("logits")
    if not isinstance(values, list) or len(values) != len(tokens) + 1:
        raise ValueError("expected one prefill logits row and one row after each generated token")
    width = None
    for row in values:
        if not isinstance(row, list) or not row:
            raise ValueError("each logits row must be a nonempty list")
        if width is None:
            width = len(row)
        if len(row) != width:
            raise ValueError("vocabulary width changes between logits rows")
        for value in row:
            if type(value) not in (int, float) or not math.isfinite(value):
                raise ValueError("logits must contain only finite numbers")
    for step, token in enumerate(tokens):
        maximum = max(range(width), key=lambda index: values[step][index])
        if token != maximum:
            raise ValueError(f"token at step {step} does not follow greedy argmax with the lowest-ID tie break")
    return values


def compare(reference, actual, *, predict=None, eos_id=None, context=None):
    """Compare exact token sequences and every logit against the frozen budget."""
    expected_rows = rows(reference)
    actual_rows = rows(actual)
    if predict is not None:
        for name, output in [("reference", reference), ("BML", actual)]:
            generated = output["tokens"]
            if len(generated) > predict:
                raise ValueError(f"{name} generated more tokens than requested")
            if len(generated) < predict and (not generated or eos_id is None or generated[-1] != eos_id):
                raise ValueError(f"{name} stopped before the requested token count without EOS")
            if eos_id in generated[:-1]:
                raise ValueError(f"{name} continued after EOS")
    if context is not None:
        for output in [reference, actual]:
            if len(output["prompt_tokens"]) + len(output["tokens"]) > context:
                raise ValueError("output exceeds the requested context")
    errors = []
    if reference["prompt_tokens"] != actual["prompt_tokens"]:
        errors.append("prompt token IDs differ")
    if reference["tokens"] != actual["tokens"]:
        errors.append("greedy generation differs")
    expected_shape = [len(expected_rows), len(expected_rows[0])]
    actual_shape = [len(actual_rows), len(actual_rows[0])]
    if expected_shape != actual_shape:
        errors.append(f"logits shapes differ: {expected_shape} vs {actual_shape}")
    violations = 0
    maximum_error = 0.0
    maximum_budget_ratio = 0.0
    first_violation = None
    if expected_shape == actual_shape:
        for step, (expected, observed) in enumerate(zip(expected_rows, actual_rows)):
            for token, (left, right) in enumerate(zip(expected, observed)):
                error = abs(right - left)
                allowed = ABSOLUTE_TOLERANCE + RELATIVE_TOLERANCE * abs(left)
                maximum_error = max(maximum_error, error)
                maximum_budget_ratio = max(maximum_budget_ratio, error / allowed)
                if error > allowed:
                    violations += 1
                    if first_violation is None:
                        first_violation = {
                            "step": step, "token": token, "reference": left,
                            "actual": right, "absolute_error": error, "allowed_error": allowed,
                        }
        if violations:
            errors.append(f"{violations} logits exceed the numerical error budget")
    if reference["bytes"] != actual["bytes"]:
        errors.append("generated output bytes differ")
    if reference["text"] != actual["text"]:
        errors.append("generated output text differs")
    return {
        "passed": not errors, "errors": errors,
        "prompt_tokens": reference["prompt_tokens"], "reference_tokens": reference["tokens"],
        "actual_tokens": actual["tokens"], "reference_shape": expected_shape,
        "actual_shape": actual_shape, "violations": violations,
        "maximum_absolute_error": maximum_error,
        "maximum_error_budget_ratio": maximum_budget_ratio,
        "first_violation": first_violation,
    }


def build_flags(source):
    """Record the relevant configured upstream build choices."""
    cache = Path(source) / "build/CMakeCache.txt"
    keys = {
        "CMAKE_BUILD_TYPE", "BUILD_SHARED_LIBS", "GGML_NATIVE", "GGML_OPENMP",
        "GGML_BLAS", "GGML_CUDA", "GGML_VULKAN", "GGML_METAL", "GGML_CPU",
    }
    result = {}
    if cache.is_file():
        for line in cache.read_text().splitlines():
            key = line.split(":", 1)[0]
            if key in keys and "=" in line:
                result[key] = line.split("=", 1)[1]
    return result


def build_reference(source, destination):
    """Link the oracle to already-built static reference libraries and record it."""
    libraries = [
        source / "build/src/libllama.a",
        source / "build/ggml/src/libggml.a",
        source / "build/ggml/src/libggml-cpu.a",
        source / "build/ggml/src/libggml-base.a",
    ]
    for library in libraries:
        if not library.is_file():
            raise ValueError(f"build the pinned llama.cpp static libraries first: missing {library}")
    compiler = os.environ.get("CXX", "c++")
    oracle = ROOT / "tools/llama_reference.cpp"
    command = [compiler, "-std=c++17", "-O2"]
    for directory in [source / "include", source / "ggml/include", source / "vendor"]:
        command.extend(["-I", str(directory)])
    command.extend([str(oracle), "-Wl,--start-group", *map(str, libraries),
                    "-Wl,--end-group", "-lpthread", "-ldl", "-lm", "-o", str(destination)])
    destination.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(command, check=True, timeout=120)
    compiler_version = subprocess.run([compiler, "--version"], check=True, capture_output=True, text=True).stdout
    manifest = {
        "schema_version": 1, "reference_revision": revision(source),
        "command": command, "compiler_version": compiler_version,
        "source_sha256": sha256(oracle), "binary_sha256": sha256(destination),
        "libraries_sha256": {str(path.relative_to(source)): sha256(path) for path in libraries},
        "build_flags": build_flags(source),
    }
    write_json(destination.with_suffix(".build.json"), manifest)
    return manifest


def reference_manifest(source, binary):
    """Reject stale provenance instead of attributing an unrelated binary to HEAD."""
    path = binary.with_suffix(".build.json")
    if not path.is_file():
        raise ValueError("reference build manifest is missing; use --build-reference")
    manifest = json.loads(path.read_text())
    if (manifest.get("reference_revision") != REFERENCE_COMMIT
            or manifest.get("binary_sha256") != sha256(binary)
            or manifest.get("source_sha256") != sha256(ROOT / "tools/llama_reference.cpp")):
        raise ValueError("reference build manifest is stale; use --build-reference")
    expected_libraries = {"build/src/libllama.a", "build/ggml/src/libggml.a",
                          "build/ggml/src/libggml-cpu.a", "build/ggml/src/libggml-base.a"}
    hashes = manifest.get("libraries_sha256", {})
    if not isinstance(hashes, dict) or hashes.keys() != expected_libraries:
        raise ValueError("reference build manifest does not identify the expected libraries")
    for name, expected_hash in hashes.items():
        if sha256(source / name) != expected_hash:
            raise ValueError("reference libraries changed since the oracle build; use --build-reference")
    return manifest


def parser():
    argument_parser = argparse.ArgumentParser(description=__doc__)
    argument_parser.add_argument("--model", type=Path, default=os.environ.get("BML_TEST_GGUF"))
    argument_parser.add_argument("--expected-model-sha256")
    argument_parser.add_argument("--bml", type=Path, default=ROOT / "target/debug/bml-model")
    argument_parser.add_argument("--reference", type=Path, default=ROOT / "target/bml-1.0/llama-reference")
    argument_parser.add_argument("--build-reference", action="store_true", help="link the oracle against existing static llama.cpp libraries and record provenance")
    argument_parser.add_argument("--llama-source", type=Path, default=ROOT / "target/bml-1.0/llama.cpp")
    argument_parser.add_argument("--artifact", type=Path, help="also compare a standalone executable, without --model")
    argument_parser.add_argument("--output", type=Path, default=ROOT / "target/bml-1.0/parity")
    argument_parser.add_argument("--timeout", type=float, default=120.0)
    argument_parser.add_argument("--context", type=int, default=128)
    return argument_parser


def main(argv=None):
    args = parser().parse_args(argv)
    if args.model is None:
        print(json.dumps({"status": "not_run", "reason": "supply --model or BML_TEST_GGUF; no model is downloaded"}))
        return 77
    if args.context < 16 or not math.isfinite(args.timeout) or args.timeout <= 0:
        raise ValueError("context must be at least 16 and timeout must be positive and finite")
    model = args.model.resolve(strict=True)
    bml = args.bml.resolve(strict=True)
    reference = args.reference.resolve()
    source = args.llama_source.resolve(strict=True)
    artifact = args.artifact.resolve(strict=True) if args.artifact else None
    args.output.mkdir(parents=True, exist_ok=True)
    report_path = args.output / "report.json"
    model_hash = sha256(model)
    if args.expected_model_sha256 and model_hash != args.expected_model_sha256.lower():
        raise ValueError("model SHA-256 does not match the expected input")
    reference_revision = revision(source)
    if reference_revision != REFERENCE_COMMIT:
        raise ValueError(f"expected llama.cpp {REFERENCE_COMMIT}, got {reference_revision}")
    dirty = subprocess.run(["git", "-C", str(source), "diff", "--quiet", "HEAD"], check=False).returncode
    if dirty:
        raise ValueError("the pinned llama.cpp source has tracked modifications")
    if args.build_reference:
        build_reference(source, reference)
    build_manifest = reference_manifest(source, reference)
    report = {
        "schema_version": 1,
        "status": "running", "created_unix": time.time(),
        "validator_source_sha256": sha256(Path(__file__)),
        "model": {"path": str(model), "sha256": model_hash, "bytes": model.stat().st_size},
        "reference": {
            "revision": reference_revision, "binary_sha256": sha256(reference),
            "build_manifest": build_manifest,
            "oracle_source_sha256": sha256(ROOT / "tools/llama_reference.cpp"),
            "build_flags": build_flags(source), "threads": 1, "kv_dtype": "f32",
            "flash_attention": False, "weight_repacking": False,
            "add_special": True, "parse_special": False,
        },
        "bml": {
            "revision": revision(ROOT), "working_tree_dirty": working_tree_dirty(ROOT),
            "binary_sha256": sha256(bml),
            "inference_sources_sha256": {
                str(path.relative_to(ROOT)): sha256(path)
                for path in sorted((ROOT / "crates/inference").rglob("*.rs"))
            },
        },
        "context": args.context,
        "tolerance": {"absolute": ABSOLUTE_TOLERANCE, "relative": RELATIVE_TOLERANCE,
                      "formula": "abs(actual-reference) <= absolute + relative*abs(reference)"},
        "cases": [],
        "limitations": ["This compares the supplied model only; it is not a throughput benchmark.",
                        "An artifact comparison alone does not prove execution in a clean isolated environment."],
    }
    if artifact:
        report["artifact"] = {"path": str(artifact), "sha256": sha256(artifact)}
    snapshot = {
        model: model_hash, bml: report["bml"]["binary_sha256"],
        reference: report["reference"]["binary_sha256"],
        ROOT / "tools/llama_reference.cpp": report["reference"]["oracle_source_sha256"],
        Path(__file__): report["validator_source_sha256"],
    }
    snapshot.update({ROOT / name: value for name, value in report["bml"]["inference_sources_sha256"].items()})
    if artifact:
        snapshot[artifact] = report["artifact"]["sha256"]
    write_json(report_path, report)
    cases = [("generation", prompt, 4) for prompt in PROMPTS]
    cases += [("tokenization", prompt, 0) for prompt in TOKENIZER_PROMPTS]
    for index, (kind, prompt, predict) in enumerate(cases):
        case = {"index": index, "kind": kind, "prompt": prompt, "predict": predict, "passed": False}
        common = ["--prompt", prompt, "--predict", str(predict), "--context", str(args.context), "--logits"]
        commands = {
            "reference": [str(reference), "--model", str(model), *common],
            "bml": [str(bml), "run", "--model", str(model), *common],
        }
        if artifact:
            commands["artifact"] = [str(artifact), *common]
        case["commands"] = commands
        try:
            expected = invoke(commands["reference"], args.output / f"case-{index:02d}-reference", args.timeout)
            eos_id = expected.get("eos_id")
            if type(eos_id) is not int or eos_id < 0:
                raise ValueError("reference output must identify the model EOS token")
            implementations = [name for name in commands if name != "reference"]
            for name in implementations:
                actual = invoke(commands[name], args.output / f"case-{index:02d}-{name}", args.timeout)
                if type(actual.get("eos_id")) is not int or actual["eos_id"] != eos_id:
                    raise ValueError(f"{name} reports a different or missing EOS token ID")
                case[name] = compare(expected, actual, predict=predict, eos_id=eos_id, context=args.context)
            case["passed"] = all(case[name]["passed"] for name in implementations)
        except (OSError, ValueError, RuntimeError, subprocess.TimeoutExpired) as error:
            case["error"] = str(error)
        report["cases"].append(case)
        write_json(report_path, report)
        print(f"{'PASS' if case['passed'] else 'FAIL'} {kind} {index}: {prompt!r}", flush=True)
    report["provenance_errors"] = changed_files(snapshot)
    report["status"] = "passed" if all(case["passed"] for case in report["cases"]) and not report["provenance_errors"] else "failed"
    report["finished_unix"] = time.time()
    write_json(report_path, report)
    print(f"{report['status']}: {report_path}")
    return 0 if report["status"] == "passed" else 1


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print(f"validation setup failed: {error}", file=sys.stderr)
        raise SystemExit(1) from error
