#!/usr/bin/env python3
"""Issue private, one-day TLS credentials for one offline fragment diagnostic.

Keys are generated by the installed OpenSSL executable directly into private
files. The issuer key never enters a runtime role directory. Public metadata
contains DER certificate fingerprints, not private-key contents or hashes.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import secrets
import shutil
import ssl
import stat
import subprocess
import sys
import time


FORMAT = "bml-fragment-run-credentials-v1"
ROLES = ("driver", "worker-0", "worker-1")
MAX_CREATION_SECONDS = 30.0


class CredentialError(RuntimeError):
    """A bounded credential-creation failure without key material in its text."""


def _check_output_path(output):
    if not output.is_absolute() or ".." in output.parts or output.parent == output:
        raise CredentialError("output must be a new absolute non-root directory")
    for parent in reversed(output.parents):
        if parent.is_symlink():
            raise CredentialError("output parent must not contain symbolic links")
    if os.path.lexists(output):
        raise CredentialError("output already exists; no files were changed")
    if not output.parent.is_dir():
        raise CredentialError("output parent directory does not exist")


def _private_directory(path):
    path.mkdir(mode=0o700)
    path.chmod(0o700)


def _private_write(path, data):
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "wb") as stream:
        os.fchmod(stream.fileno(), 0o600)
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())


def _run(openssl, arguments, phase, deadline):
    remaining = deadline - time.monotonic()
    if remaining <= 0:
        raise CredentialError(f"credential creation deadline exceeded during {phase}")
    try:
        result = subprocess.run(
            [openssl, *arguments],
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
            timeout=min(10.0, remaining),
            umask=0o077,
        )
    except subprocess.TimeoutExpired:
        raise CredentialError(f"OpenSSL timed out during {phase}") from None
    except OSError:
        raise CredentialError(f"OpenSSL could not execute during {phase}") from None
    if result.returncode:
        # Never echo child output: only public phase names and the exit status.
        raise CredentialError(f"OpenSSL failed during {phase} (exit {result.returncode})")
    return result.stdout


def _certificate_sha256(path):
    try:
        der = ssl.PEM_cert_to_DER_cert(path.read_text(encoding="ascii"))
    except (UnicodeError, ValueError, OSError):
        raise CredentialError("could not decode generated certificate") from None
    return hashlib.sha256(der).hexdigest()


def _certificate_serial():
    # Serials are public identifiers, never secret key material.
    return hex(int(secrets.token_hex(16), 16) or 1)


def _check_private_tree(output):
    for path in [output, *output.rglob("*")]:
        details = path.lstat()
        if stat.S_ISDIR(details.st_mode):
            expected = 0o700
        elif stat.S_ISREG(details.st_mode):
            expected = 0o600
        else:
            raise CredentialError("generated tree contains a non-regular entry")
        if stat.S_IMODE(details.st_mode) != expected:
            raise CredentialError("generated entry has unexpected access permissions")


def _ca_config(run_id):
    return f"""[req]
prompt = no
distinguished_name = dn
x509_extensions = v3_ca
[dn]
CN = BML fragment run {run_id}
[v3_ca]
basicConstraints = critical,CA:TRUE,pathlen:0
keyUsage = critical,keyCertSign,cRLSign
subjectKeyIdentifier = hash
authorityKeyIdentifier = keyid:always
""".encode("ascii")


def _leaf_config(name, purpose):
    return f"""[req]
prompt = no
distinguished_name = dn
[dn]
CN = {name}
[v3_leaf]
basicConstraints = critical,CA:FALSE
keyUsage = critical,digitalSignature
extendedKeyUsage = {purpose}
subjectAltName = DNS:{name}
subjectKeyIdentifier = hash
authorityKeyIdentifier = keyid:always
""".encode("ascii")


def create(output):
    """Create a new private credential tree and return its public manifest.

    ``output`` must be an absolute, nonexistent directory with an existing
    non-symlink parent. No network is used. If issuing fails, private partial
    state remains in place and no success manifest is emitted.
    """
    output = Path(output)
    try:
        _check_output_path(output)
    except OSError:
        raise CredentialError("could not inspect the output directory safely") from None
    openssl = shutil.which("openssl")
    if openssl is None:
        raise CredentialError("installed OpenSSL executable is required")
    deadline = time.monotonic() + MAX_CREATION_SECONDS
    version_bytes = _run(openssl, ["version"], "version check", deadline)
    try:
        version = version_bytes.decode("ascii").strip()
    except UnicodeError:
        raise CredentialError("OpenSSL returned an invalid version string") from None
    if not version.startswith("OpenSSL 3.") or len(version) > 256 or "\n" in version:
        raise CredentialError("this diagnostic requires the installed OpenSSL 3 executable")
    run_id = secrets.token_hex(16)
    try:
        _private_directory(output)
    except OSError:
        raise CredentialError("could not create new private output directory") from None
    phase = "prepare private directories"
    try:
        issuer = output / "issuer"
        runtime = output / "runtime"
        _private_directory(issuer)
        _private_directory(runtime)
        ca_key = issuer / "ca.key"
        ca_cert = issuer / "ca.crt"
        ca_config = issuer / "ca.cnf"
        _private_write(ca_config, _ca_config(run_id))
        phase = "generate issuer key"
        _run(openssl, ["genpkey", "-algorithm", "EC", "-pkeyopt",
                       "ec_paramgen_curve:P-256", "-out", str(ca_key)], phase, deadline)
        phase = "sign issuer certificate"
        _run(openssl, ["req", "-new", "-x509", "-sha256", "-days", "1",
                       "-key", str(ca_key), "-out", str(ca_cert),
                       "-set_serial", _certificate_serial(),
                       "-config", str(ca_config)], phase, deadline)
        roles = {}
        for role in ROLES:
            directory = runtime / role
            _private_directory(directory)
            name = f"{role}.{run_id}.bml.invalid"
            key = directory / "key.key"
            cert = directory / "cert.crt"
            ca_copy = directory / "ca.crt"
            config = issuer / f"{role}.cnf"
            request = issuer / f"{role}.csr"
            purpose = "clientAuth" if role == "driver" else "serverAuth"
            _private_write(config, _leaf_config(name, purpose))
            phase = f"generate {role} key"
            _run(openssl, ["genpkey", "-algorithm", "EC", "-pkeyopt",
                           "ec_paramgen_curve:P-256", "-out", str(key)], phase, deadline)
            phase = f"request {role} certificate"
            _run(openssl, ["req", "-new", "-sha256", "-key", str(key),
                           "-out", str(request), "-config", str(config)], phase, deadline)
            phase = f"sign {role} certificate"
            _run(openssl, ["x509", "-req", "-in", str(request),
                           "-CA", str(ca_cert), "-CAkey", str(ca_key),
                           "-set_serial", _certificate_serial(),
                           "-days", "1", "-sha256", "-extfile", str(config),
                           "-extensions", "v3_leaf", "-out", str(cert)], phase, deadline)
            _private_write(ca_copy, ca_cert.read_bytes())
            phase = f"verify {role} certificate"
            _run(openssl, ["verify", "-CAfile", str(ca_copy), "-purpose",
                           "sslclient" if role == "driver" else "sslserver",
                           "-verify_hostname", name, str(cert)], phase, deadline)
            roles[role] = {
                "certificate_sha256": _certificate_sha256(cert),
                "server_name": name,
                "files": {
                    "ca_certificate": ca_copy.relative_to(output).as_posix(),
                    "certificate": cert.relative_to(output).as_posix(),
                    "private_key": key.relative_to(output).as_posix(),
                },
            }
        manifest = {
            "format": FORMAT,
            "run_id": run_id,
            "openssl_version": version,
            "ca_certificate_sha256": _certificate_sha256(ca_cert),
            "roles": roles,
        }
        phase = "verify private permissions"
        _check_private_tree(output)
        phase = "write public manifest"
        _private_write(output / "manifest.json",
                       (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode())
        return manifest
    except (CredentialError, OSError) as error:
        message = str(error) if isinstance(error, CredentialError) else f"filesystem failure during {phase}"
        # The output exists exclusively for this run. Preserve incomplete issuer
        # and role files with the same restrictive permissions; never delete keys.
        try:
            _private_write(output / "creation-failed.json",
                           (json.dumps({"status": "incomplete", "phase": phase,
                                        "error": message}) + "\n").encode())
        except OSError:
            pass
        raise CredentialError(message) from None


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True,
                        help="new absolute directory for this run's private credentials")
    arguments = parser.parse_args(argv)
    try:
        manifest = create(arguments.output)
    except CredentialError as error:
        print(f"fragment credentials: {error}", file=sys.stderr)
        return 1
    print(json.dumps(manifest, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
